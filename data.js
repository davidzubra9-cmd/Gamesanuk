SP.getGame = function (id) {
  for (var i = 0; i < SP.gameList.length; i++) if (SP.gameList[i].id === id) return SP.gameList[i];
  return null;
};
SP.getCat = function (id) {
  for (var i = 0; i < SP.categories.length; i++) if (SP.categories[i].id === id) return SP.categories[i];
  return null;
};
SP.inputLabel = function (g) {
  var m = { mouse: '🖱️', touch: '👆', keys: '⌨️' };
  return (g.input || []).map(function (k) { return m[k] || ''; }).join(' ');
};
